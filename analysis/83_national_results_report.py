def interval(row, scale=100):
    return f'{row.probability_difference*scale:+.2f} [{row.ci_low*scale:+.2f}; {row.ci_high*scale:+.2f}]'

def table(headers, rows):
    return '\n'.join(['| '+' | '.join(headers)+' |', '| '+' | '.join(['---']*len(headers))+' |']
                     + ['| '+' | '.join(map(str,r))+' |' for r in rows])

