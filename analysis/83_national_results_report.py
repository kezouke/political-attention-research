    assert checks['input_hashes_match'] and checks['probability_checks_passed']
    m=pd.read_csv(P/'national_model_margins.csv')
    v=pd.read_csv(P/'national_incremental_validation.csv')
    counts=pd.read_csv(P/'national_locked_counts.csv')
    rows=[]
    for key,name in NAMES.items():
        d=m[(m.dataset==key)&(m.target=='government_vs_opposition')&(m.outcome==1)].set_index('variable')
        rows.append([name,int(d.iloc[0]['n']),interval(d.loc['economy_bad']),interval(d.loc['government_disapproval'])])
    government=table(['Опрос','Человек','Хуже экономика','Хуже оценка кабинета'],rows)
